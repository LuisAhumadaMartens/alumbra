ROOT = pathlib.Path(__file__).resolve().parents[2]
TOKENS = ROOT / "design/tokens"
DESCRIPTION = "Fixture token used by the generator tests."


def color(space, components, alpha=None):
    value = {"colorSpace": space, "components": components}
    if alpha is not None:
        value["alpha"] = alpha
    return value


class Fixture:
    def __init__(self):
        self.directory = tempfile.TemporaryDirectory()
        self.root = pathlib.Path(self.directory.name) / "tokens"
        shutil.copytree(TOKENS, self.root)

    def edit(self, name, change):
        path = self.root / name
        data = json.loads(path.read_text(encoding="utf-8"))
        change(data)
        path.write_text(json.dumps(data, indent=2), encoding="utf-8")

    def load(self):
        return token_model.load(self.root)

    def close(self):
        self.directory.cleanup()


def documented(value, kind=None, **extra):
    token = {"$value": value, "$description": DESCRIPTION, **extra}
    if kind:
        token["$type"] = kind
    return token


def component(value):
    return documented(value, "color", **{
        "$extensions": {"com.alumbra": {"tier": "component", "stability": "experimental"}}
    })


class NamingTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.catalogue = token_model.load(TOKENS)
        cls.outputs = generate_tokens.render(cls.catalogue)

    def test_underscore_and_dot_paths_map_to_distinct_names(self):
        underscore = self.catalogue.by_name["player.ad_band.background"]
        dotted = self.catalogue.by_name["player.ad.band.background"]
        self.assertEqual(underscore.css, "--alumbra-player-ad_band-background")
        self.assertEqual(dotted.css, "--alumbra-player-ad-band-background")
        self.assertEqual(underscore.identifier, "alumbra_token_player_sad_uband_sbackground")
        self.assertEqual(dotted.identifier, "alumbra_token_player_sad_sband_sbackground")

    def test_every_output_names_both_example_paths(self):
        expected = {
            token_model.CSS_PATH: ("--alumbra-player-ad_band-background",
                                   "--alumbra-player-ad-band-background"),
        }
        identifiers = ("alumbra_token_player_sad_uband_sbackground",
                       "alumbra_token_player_sad_sband_sbackground")
        for path in (token_model.TS_PATH, token_model.SWIFT_PATH, token_model.KOTLIN_PATH,
                     token_model.CPP_PATH, token_model.DOCS_PATH):
            expected[path] = identifiers
        for path, names in expected.items():
            for name in names:
                with self.subTest(path=path, name=name):
                    self.assertIn(name, self.outputs[path])

    def test_identifier_encoding_is_injective(self):
        cases = {
            ("a_b", "c"): "alumbra_token_a_ub_sc",
            ("a", "b_c"): "alumbra_token_a_sb_uc",
            ("a", "b", "c"): "alumbra_token_a_sb_sc",
            ("a_b_c",): "alumbra_token_a_ub_uc",
            ("color", "neutral", "900"): "alumbra_token_color_sneutral_s900",
        }
        for segments, expected in cases.items():
            self.assertEqual(token_model.identifier(segments), expected)
        self.assertEqual(len(set(cases.values())), len(cases))

    def test_root_maps_to_its_group_path(self):
        token = self.catalogue.by_path[("player", "button", "background", "$root")]
        self.assertEqual(token.name, "player.button.background")
        self.assertEqual(token.css, "--alumbra-player-button-background")
        self.assertEqual(token.identifier, "alumbra_token_player_sbutton_sbackground")
        self.assertNotIn("$root", self.outputs[token_model.CSS_PATH])
        self.assertNotIn("_sroot", self.outputs[token_model.CPP_PATH])

    def test_collisions_are_rejected(self):
        class Fake:
            def __init__(self, path, name):
                self.path, self.name = path, name
                self.css, self.identifier = name, name

        with self.assertRaisesRegex(ValueError, "generated by both a.b and c"):
            token_model.check_collisions([Fake(("a", "b"), "x"), Fake(("c",), "x")])

    def test_typed_outputs_expose_only_semantic_and_component_tokens(self):
        primitive = self.catalogue.by_name["color.neutral.900"]
        self.assertIn(primitive.css, self.outputs[token_model.CSS_PATH])
        for path in (token_model.TS_PATH, token_model.SWIFT_PATH, token_model.KOTLIN_PATH,
                     token_model.CPP_PATH):
            with self.subTest(path=path):
                self.assertNotIn(primitive.identifier, self.outputs[path])


class ModesTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.catalogue = token_model.load(TOKENS)
        cls.outputs = generate_tokens.render(cls.catalogue)

    def test_every_context_is_emitted_in_every_output(self):
        css = self.outputs[token_model.CSS_PATH]
        for modifier in self.catalogue.modifiers:
            for context in modifier.contexts:
                with self.subTest(modifier=modifier.name, context=context):
                    if context != modifier.default:
                        self.assertIn(f'[data-alumbra-{modifier.name}="{context}"]', css)
                    self.assertIn(json.dumps(context), self.outputs[token_model.TS_PATH])
                    self.assertIn(f"case {token_model.camel(context, False)}",
                                  self.outputs[token_model.SWIFT_PATH])
                    self.assertIn(f'{context.upper()}("{context}")',
                                  self.outputs[token_model.KOTLIN_PATH])
                    self.assertIn(f"k{token_model.camel(context, True)}",
                                  self.outputs[token_model.CPP_PATH])
        for query in token_model.MEDIA.values():
            self.assertIn(f"@media {query}", css)

    def test_resolver_values_depend_only_on_declared_modifiers(self):
        surface = self.catalogue.by_name["color.surface.base"]
        self.assertEqual([item.name for item in surface.modifiers], ["theme", "contrast"])
        self.assertEqual(len(surface.table), 4)
        target = self.catalogue.by_name["target.minimum"]
        self.assertEqual([item.name for item in target.modifiers], ["density"])
        self.assertEqual(target.table, [48.0, 48.0, 44.0, 72.0])
        self.assertEqual(self.catalogue.by_name["player.button.background"].alias,
                         "color.control.background")

    def test_generation_is_deterministic_and_committed(self):
        again = generate_tokens.render(token_model.load(TOKENS))
        self.assertEqual(again, self.outputs)
        with redirect_stderr(io.StringIO()) as errors:
            self.assertEqual(generate_tokens.main(["--check", "--root", str(ROOT)]), 0,
                             errors.getvalue())


class GoldenTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.catalogue = token_model.load(TOKENS)
        cls.css = generate_tokens.render(cls.catalogue)[token_model.CSS_PATH]

    def document(self):
        contexts = {
            golden_tokens.context_key(self.catalogue, index): {
                token.name: token.values[index] for token in self.catalogue.public
            }
            for index in range(len(self.catalogue.selections))
        }
        scenarios = {
            name: golden_tokens.expected_scenario(
                self.catalogue,
                {override: golden_tokens.sentinel(override) for override in overrides})
            for name, overrides in golden_tokens.SCENARIOS.items()
        }
        return {"language": "fixture", "contexts": contexts, "scenarios": scenarios}

    def test_css_matches_the_resolver_in_every_context(self):
        self.assertEqual(golden_tokens.check_css(self.catalogue, self.css), [])

    def test_css_mutations_are_detected(self):
        mutations = {
            "value": self.css.replace("--alumbra-target-size-minimum: 72px;",
                                      "--alumbra-target-size-minimum: 70px;"),
            "context": self.css.replace('[data-alumbra-dynamic-range="hdr"]',
                                        '[data-alumbra-dynamic-range="sdr"]'),
            "alias": self.css.replace(
                "--alumbra-player-button-background-focus: var(--alumbra-color-control-background);",
                "--alumbra-player-button-background-focus: var(--alumbra-color-control-hover);"),
        }
        for name, css in mutations.items():
            with self.subTest(name=name):
                self.assertNotEqual(css, self.css)
                self.assertTrue(golden_tokens.check_css(self.catalogue, css))

    def test_dump_comparison_detects_value_context_and_scenario_drift(self):
        document = self.document()
        self.assertEqual(golden_tokens.check_dump(self.catalogue, document), [])
        drifted = copy.deepcopy(document)
        drifted["contexts"]["dark/normal/tv/full/sdr"]["target.minimum"] = 70.0
        self.assertTrue(golden_tokens.check_dump(self.catalogue, drifted))
        missing = copy.deepcopy(document)
        del missing["contexts"]["light/high/phone/reduced/hdr"]
        self.assertTrue(golden_tokens.check_dump(self.catalogue, missing))
        explicit = copy.deepcopy(document)
        explicit["scenarios"]["component"]["player.button.background.focus"] = (
            golden_tokens.sentinel("color.control.background"))
        self.assertTrue(golden_tokens.check_dump(self.catalogue, explicit))

    def test_scenarios_reresolve_aliases_and_keep_explicit_overrides(self):
        semantic = golden_tokens.sentinel("color.control.background")
        focus = golden_tokens.sentinel("player.button.background.focus")
        values = golden_tokens.expected_scenario(self.catalogue, {
            "color.control.background": semantic,
            "player.button.background.focus": focus,
        })
        self.assertEqual(values["player.button.background"], semantic)
        self.assertEqual(values["player.ad_chrome.badge.background"], semantic)
        self.assertEqual(values["player.button.background.focus"], focus)
        self.assertNotEqual(values["player.button.background.hover"], semantic)


class FixtureTest(unittest.TestCase):
    def setUp(self):
        self.fixture = Fixture()
        self.addCleanup(self.fixture.close)

    def test_wide_gamut_colors_get_srgb_fallbacks_and_guarded_css(self):
        def primitives(data):
            data["color"]["wide"] = {
                "p3": documented(color("display-p3", [1, 0.2, 0.1])),
                "rec": documented(color("rec2020", [0.1, 0.8, 0.3], 0.5)),
            }

        def semantic(data):
            data["color"]["vivid"] = {
                "$type": "color",
                "p3": documented("{color.wide.p3}"),
                "rec": documented("{color.wide.rec}"),
            }

        self.fixture.edit("primitives.tokens.json", primitives)
        self.fixture.edit("semantic.tokens.json", semantic)
        catalogue = self.fixture.load()
        outputs = generate_tokens.render(catalogue)
        p3 = catalogue.by_name["color.vivid.p3"].values[0]
        self.assertEqual(p3["colorSpace"], "display-p3")
        self.assertTrue(all(0 <= part <= 1 for part in p3["srgb"]))
        css = outputs[token_model.CSS_PATH]
        self.assertIn("@media (color-gamut: p3) {\n  @supports (color: color(display-p3 0 0 0))", css)
        self.assertIn("--alumbra-color-wide-p3: color(display-p3 1 0.2 0.1);", css)
        self.assertIn("--alumbra-color-wide-rec: color(rec2020 0.1 0.8 0.3 / 50%);", css)
        self.assertEqual(golden_tokens.check_css(catalogue, css), [])
        self.assertIn('wide("display-p3", 1.0, 0.2, 0.1, 1.0', outputs[token_model.TS_PATH])
        self.assertIn("wide(.displayP3, 1.0, 0.2, 0.1, 1.0", outputs[token_model.SWIFT_PATH])
        self.assertIn("wide(ColorSpace.REC2020, 0.1, 0.8, 0.3, 0.5",
                      outputs[token_model.KOTLIN_PATH])
        self.assertIn(".color_space = ColorSpace::kDisplayP3,", outputs[token_model.CPP_PATH])

    def test_units_convert_for_platforms_and_stay_authored_in_css(self):
        def primitives(data):
            data["space"]["20"] = documented({"value": 1.5, "unit": "rem"})
            data["motion"]["time"]["slow"] = documented({"value": 0.5, "unit": "s"}, "duration")

        def semantic(data):
            data["spacing"]["huge"] = documented("{space.20}")
            data["motion"]["duration"]["slow"] = documented("{motion.time.slow}")

        self.fixture.edit("primitives.tokens.json", primitives)
        self.fixture.edit("semantic.tokens.json", semantic)
        catalogue = self.fixture.load()
        css = generate_tokens.render(catalogue)[token_model.CSS_PATH]
        self.assertEqual(catalogue.by_name["spacing.huge"].table, [24.0])
        self.assertIn("--alumbra-space-20: 1.5rem;", css)
        self.assertEqual(catalogue.by_name["motion.duration.slow"].table, [500.0])
        self.assertIn("--alumbra-motion-time-slow: 0.5s;", css)
        self.assertEqual(golden_tokens.check_css(catalogue, css), [])

    def test_deprecated_alias_forwards_overrides_to_its_replacement(self):
        def semantic(data):
            data["color"]["surface"]["canvas"] = documented(
                "{color.surface.base}", **{"$deprecated": "Use color.surface.base."})

        self.fixture.edit("semantic.tokens.json", semantic)
        catalogue = self.fixture.load()
        outputs = generate_tokens.render(catalogue)
        deprecated = catalogue.by_name["color.surface.canvas"]
        self.assertEqual(deprecated.replacement, "color.surface.base")
        css = outputs[token_model.CSS_PATH]
        self.assertIn(
            "--alumbra-color-surface-base: var(--alumbra-color-surface-canvas, "
            "var(--alumbra-color-scheme-normal-surface));", css)
        self.assertNotIn("--alumbra-color-surface-canvas:", css)
        self.assertEqual(golden_tokens.check_css(catalogue, css), [])
        self.assertIn(
            "overrides.alumbra_token_color_ssurface_sbase ?? "
            "overrides.alumbra_token_color_ssurface_scanvas ??", outputs[token_model.TS_PATH])
        self.assertIn("kColorDeprecations", outputs[token_model.CPP_PATH])
        replaced = golden_tokens.expected_scenario(
            catalogue, {"color.surface.canvas": golden_tokens.sentinel("color.control.background")})
        self.assertEqual(replaced["color.surface.base"],
                         golden_tokens.sentinel("color.control.background"))
        self.assertEqual(replaced["color.surface.canvas"], replaced["color.surface.base"])

    def test_context_dependent_public_alias_is_rejected(self):
        def contrast(data):
            data["player"] = {"focus": {"ring": {"$root": component("{color.text.primary}")}}}

        self.fixture.edit("contexts/contrast-high.tokens.json", contrast)
        with self.assertRaisesRegex(ValueError, "changes its public alias target"):
            self.fixture.load()

    def test_contexts_cannot_add_tokens(self):
        def motion(data):
            data["motion"]["time"]["extra"] = documented({"value": 1, "unit": "ms"})

        self.fixture.edit("contexts/motion-reduced.tokens.json", motion)
        with self.assertRaisesRegex(ValueError, "must not add or remove tokens"):
            self.fixture.load()


class GamutTest(unittest.TestCase):
    def test_srgb_is_returned_unchanged(self):
        self.assertEqual(color_gamut.srgb_fallback("srgb", [0.059, 0.09, 0.165]),
                         (0.059, 0.09, 0.165))

    def test_in_gamut_display_p3_converts_exactly_to_srgb(self):
        self.assertEqual(color_gamut.srgb_fallback("display-p3", [1, 1, 1]), (1.0, 1.0, 1.0))
        self.assertEqual(color_gamut.srgb_fallback("display-p3", [0, 0, 0]), (0.0, 0.0, 0.0))
        middle = color_gamut.srgb_fallback("display-p3", [0.5, 0.5, 0.5])
        self.assertTrue(all(abs(part - 0.5) < 0.0001 for part in middle))

    def test_out_of_gamut_colors_map_into_srgb_preserving_hue(self):
        for space, components in (("display-p3", [1, 0, 0]), ("rec2020", [0, 1, 0])):
            with self.subTest(space=space):
                fallback = color_gamut.srgb_fallback(space, components)
                self.assertTrue(all(0 <= part <= 1 for part in fallback))
                self.assertEqual(max(fallback), fallback[components.index(1)])
                self.assertEqual(fallback, color_gamut.srgb_fallback(space, components))


